-- Cambios aditivos para los recordatorios de citas y derivaciones clínicas del chat.
-- Ejecutar una sola vez sobre la base PostgreSQL de la clínica antes de iniciar la nueva API.

CREATE TABLE IF NOT EXISTS appointment_reminders (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id integer NOT NULL UNIQUE REFERENCES appointments(id) ON DELETE CASCADE,
    scheduled_at_utc timestamp with time zone NOT NULL,
    sent_at_utc timestamp with time zone NULL,
    attempts integer NOT NULL DEFAULT 0,
    last_error character varying(500) NULL,
    created_at_utc timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_appointment_reminders_due
    ON appointment_reminders (scheduled_at_utc)
    WHERE sent_at_utc IS NULL;

CREATE TABLE IF NOT EXISTS chat_clinical_escalations (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id integer NULL REFERENCES chat_conversations(id) ON DELETE SET NULL,
    created_by_user_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    patient_id integer NULL REFERENCES patients(id) ON DELETE SET NULL,
    summary character varying(1000) NOT NULL,
    urgency character varying(20) NOT NULL DEFAULT 'normal',
    status character varying(20) NOT NULL DEFAULT 'pending',
    created_at_utc timestamp with time zone NOT NULL DEFAULT now(),
    resolved_at_utc timestamp with time zone NULL,
    CONSTRAINT ck_chat_clinical_escalations_urgency CHECK (urgency IN ('normal', 'alta')),
    CONSTRAINT ck_chat_clinical_escalations_status CHECK (status IN ('pending', 'resolved'))
);

CREATE INDEX IF NOT EXISTS idx_chat_clinical_escalations_pending
    ON chat_clinical_escalations (status, created_at_utc DESC);

CREATE TABLE IF NOT EXISTS chat_appointment_escalations (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id integer NULL REFERENCES chat_conversations(id) ON DELETE SET NULL,
    created_by_user_id integer NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    appointment_id integer NULL REFERENCES appointments(id) ON DELETE SET NULL,
    summary character varying(1000) NOT NULL,
    status character varying(20) NOT NULL DEFAULT 'pending',
    created_at_utc timestamp with time zone NOT NULL DEFAULT now(),
    resolved_at_utc timestamp with time zone NULL,
    CONSTRAINT ck_chat_appointment_escalations_status CHECK (status IN ('pending', 'resolved'))
);

CREATE INDEX IF NOT EXISTS idx_chat_appointment_escalations_pending
    ON chat_appointment_escalations (status, created_at_utc DESC);
